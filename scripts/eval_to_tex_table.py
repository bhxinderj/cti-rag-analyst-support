#!/usr/bin/env python3
"""
Render the _final_v1 evaluation artifacts as LaTeX tables (booktabs).

Reads the artifact groups in data/evaluation_results/setup_b/ and writes:
  - ragas_final_v1.tex   — RAGAS metrics, mean +/- std over n runs per row
  - rubric_final_v1.tex  — Structured-Rubric dimensions (0-3 scale)

Rows are discovered by filename pattern; the hosted-generation ablation
row appears automatically once its artifact exists. Cells with n=1 show
the plain value (no std); the best value per metric column across the
retrieval pipelines is set in bold. Baseline cells for retrieval-only
metrics render as ---.

Usage:
    .venv/bin/python scripts/eval_to_tex_table.py [--out-dir thesis/tables]
"""

from __future__ import annotations

import argparse
import glob
import json
import statistics as st
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ARTIFACT_DIR = REPO_ROOT / "data" / "evaluation_results" / "setup_b"

RAGAS_METRICS = [
    ("faithfulness", "Faithfulness"),
    ("answer_relevancy", "Answer Relevancy"),
    ("answer_correctness", "Answer Correctness"),
    ("context_precision", "Context Precision"),
    ("context_recall", "Context Recall"),
]

# (row label, glob pattern, counts toward per-column bolding)
RAGAS_ROWS = [
    ("Templated hybrid (local 8B)", "ragas_hybrid_templated_final_v1_r*.json", True),
    ("Legacy hybrid (local 8B)", "ragas_hybrid_final_v1_r*.json", True),
    ("BM25 only", "ragas_bm25_final_v1_r*.json", True),
    ("Vector only", "ragas_vector_final_v1_r*.json", True),
    ("No-retrieval baseline", "ragas_baseline_final_v1_r*.json", False),
    (
        "Templated hybrid (hosted, Haiku 4.5)",
        "ragas_hybrid_templated_hostedgen_haiku45_final_v1*.json",
        False,
    ),
]

RUBRIC_DIMS = [
    ("prioritization_mean", "Prioritization"),
    ("actionability_mean", "Actionability"),
    ("completeness_mean", "Completeness"),
    ("traceability_mean", "Traceability"),
    ("total_mean", "Total"),
]

RUBRIC_ROWS = [
    ("Templated hybrid", "rubric_hybrid_templated_final_v1_r*.json"),
    ("Legacy hybrid", "rubric_hybrid_final_v1_r*.json"),
    ("No-retrieval baseline", "rubric_baseline_final_v1_r*.json"),
    (
        "Templated hybrid (hosted, Haiku 4.5)",
        "rubric_hybrid_templated_hostedgen_haiku45_final_v1_*.json",
    ),
]


def _load_group(pattern: str) -> list[dict]:
    return [json.load(open(f)) for f in sorted(glob.glob(str(ARTIFACT_DIR / pattern)))]


def _mean_std(values: list[float]) -> tuple[float, float | None]:
    if len(values) >= 2:
        return st.mean(values), st.stdev(values)
    return values[0], None


def _cell(mean: float, std: float | None, bold: bool, decimals: int = 3) -> str:
    body = f"{mean:.{decimals}f}"
    if std is not None:
        body += f" $\\pm$ {std:.{decimals}f}"
    return f"\\textbf{{{body}}}" if bold else body


def build_ragas_table() -> str:
    rows_data = []
    for label, pattern, bold_eligible in RAGAS_ROWS:
        runs = _load_group(pattern)
        if not runs:
            continue
        cells = {}
        for key, _ in RAGAS_METRICS:
            vals = [r["metrics"][key] for r in runs if key in r["metrics"]]
            cells[key] = _mean_std(vals) if vals else None
        rows_data.append((label, len(runs), cells, bold_eligible))

    best = {}
    for key, _ in RAGAS_METRICS:
        candidates = [
            cells[key][0]
            for _, _, cells, eligible in rows_data
            if eligible and cells.get(key)
        ]
        best[key] = max(candidates) if candidates else None

    lines = [
        "% Auto-generated by scripts/eval_to_tex_table.py — do not edit by hand.",
        "% Requires \\usepackage{booktabs}.",
        "\\begin{tabular}{lrccccc}",
        "\\toprule",
        "Pipeline & $n$ & "
        + " & ".join(label for _, label in RAGAS_METRICS)
        + " \\\\",
        "\\midrule",
    ]
    for label, n, cells, eligible in rows_data:
        rendered = []
        for key, _ in RAGAS_METRICS:
            if cells.get(key) is None:
                rendered.append("---")
                continue
            mean, std = cells[key]
            is_best = eligible and best[key] is not None and abs(mean - best[key]) < 1e-9
            rendered.append(_cell(mean, std, is_best))
        lines.append(f"{label} & {n} & " + " & ".join(rendered) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def build_rubric_table() -> str:
    lines = [
        "% Auto-generated by scripts/eval_to_tex_table.py — do not edit by hand.",
        "% Requires \\usepackage{booktabs}. Scale: 0--3 per dimension.",
        "\\begin{tabular}{lrccccc}",
        "\\toprule",
        "Pipeline & $n$ & "
        + " & ".join(label for _, label in RUBRIC_DIMS)
        + " \\\\",
        "\\midrule",
    ]
    for label, pattern in RUBRIC_ROWS:
        runs = _load_group(pattern)
        if not runs:
            continue
        cells = []
        for key, _ in RUBRIC_DIMS:
            vals = [r["aggregated"][key] for r in runs]
            mean, std = _mean_std(vals)
            cells.append(_cell(mean, std, bold=False, decimals=2))
        lines.append(f"{label} & {len(runs)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default=str(REPO_ROOT / "thesis" / "tables"))
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    targets = {
        "ragas_final_v1.tex": build_ragas_table(),
        "rubric_final_v1.tex": build_rubric_table(),
    }
    for name, content in targets.items():
        path = out_dir / name
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
